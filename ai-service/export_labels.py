"""
Generate MySQL rows for every class the model was trained on.

The original schema.sql seeded only 12 disease rows. A model trained on the
full PlantVillage + PlantDoc taxonomy predicts 38 classes, and any class
without a matching `diseases.class_label` row makes PredictionService throw
"Unknown class label from AI service". This closes that gap by emitting the
species and disease rows straight from the trained label order.

Hindi names are provided for the plants and the common diseases; anything
without a translation is emitted with a TODO marker rather than a
machine-guessed name, since a wrong disease name in a farmer's language is
worse than an obviously untranslated one.

Run:
    python export_labels.py --labels models/labels.json --out ../database/seed_classes.sql
"""
import argparse
import json
from pathlib import Path

from labels import CANONICAL, HAS_REAL_WORLD_DATA, pretty

PLANT_HI = {
    "Apple": "सेब", "Blueberry": "ब्लूबेरी", "Cherry": "चेरी", "Corn": "मक्का",
    "Grape": "अंगूर", "Orange": "संतरा", "Peach": "आड़ू", "Pepper_bell": "शिमला मिर्च",
    "Potato": "आलू", "Raspberry": "रसभरी", "Soybean": "सोयाबीन", "Squash": "कद्दू",
    "Strawberry": "स्ट्रॉबेरी", "Tomato": "टमाटर",
}

PLANT_CATEGORY = {
    "Corn": "foodgrain", "Potato": "foodgrain", "Soybean": "foodgrain",
    "Apple": "horticulture", "Blueberry": "horticulture", "Cherry": "horticulture",
    "Grape": "horticulture", "Orange": "horticulture", "Peach": "horticulture",
    "Pepper_bell": "horticulture", "Raspberry": "horticulture",
    "Squash": "horticulture", "Strawberry": "horticulture", "Tomato": "horticulture",
}

DISEASE_HI = {
    "healthy": ("स्वस्थ", "none"),
    "Apple_scab": ("सेब की पपड़ी रोग", "moderate"),
    "Black_rot": ("काला सड़न रोग", "severe"),
    "Cedar_apple_rust": ("देवदार-सेब रतुआ रोग", "moderate"),
    "Powdery_mildew": ("चूर्णिल आसिता", "moderate"),
    "Cercospora_leaf_spot_Gray_leaf_spot": ("सर्कोस्पोरा धूसर पर्ण धब्बा", "moderate"),
    "Common_rust": ("सामान्य रतुआ रोग", "moderate"),
    "Northern_Leaf_Blight": ("उत्तरी पर्ण अंगमारी", "moderate"),
    "Esca_Black_Measles": ("एस्का (काला खसरा) रोग", "severe"),
    "Leaf_blight_Isariopsis_Leaf_Spot": ("पर्ण अंगमारी", "moderate"),
    "Haunglongbing_Citrus_greening": ("सिट्रस ग्रीनिंग रोग", "severe"),
    "Bacterial_spot": ("जीवाणु धब्बा रोग", "moderate"),
    "Early_blight": ("अगेती झुलसा रोग", "moderate"),
    "Late_blight": ("पछेती झुलसा रोग", "severe"),
    "Leaf_Mold": ("पर्ण फफूंद रोग", "moderate"),
    "Septoria_leaf_spot": ("सेप्टोरिया पर्ण धब्बा", "moderate"),
    "Spider_mites_Two_spotted_spider_mite": ("मकड़ी घुन (दो-धब्बेदार)", "moderate"),
    "Target_Spot": ("लक्ष्य धब्बा रोग", "moderate"),
    "Tomato_Yellow_Leaf_Curl_Virus": ("टमाटर पीला पर्ण मरोड़ विषाणु", "severe"),
    "Tomato_mosaic_virus": ("टमाटर मोज़ेक विषाणु", "severe"),
    "Leaf_scorch": ("पर्ण दाह रोग", "moderate"),
}


def sql_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "''")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", default="models/labels.json",
                    help="labels.json written by train.py")
    ap.add_argument("--out", default="../database/seed_classes.sql")
    args = ap.parse_args()

    labels_file = Path(args.labels)
    if labels_file.exists():
        class_names = json.loads(labels_file.read_text())["class_names"]
        print(f"Using trained label order from {labels_file} ({len(class_names)} classes)")
    else:
        class_names = CANONICAL
        print(f"{labels_file} not found — falling back to the full canonical list "
              f"({len(class_names)} classes). Train first for the exact order.")

    plants = sorted({c.partition("___")[0] for c in class_names})
    todos = []
    lines = [
        "-- Generated by ai-service/export_labels.py — do not hand-edit.",
        "-- Seeds plant_species and diseases for every class the CNN predicts,",
        "-- so diseases.class_label joins directly to model output.",
        "USE agriplant_ai;",
        "",
        "-- Existing seed rows from schema.sql are replaced to keep class_label unique.",
        "SET FOREIGN_KEY_CHECKS = 0;",
        "TRUNCATE TABLE care_guides;",
        "TRUNCATE TABLE diseases;",
        "TRUNCATE TABLE plant_species;",
        "SET FOREIGN_KEY_CHECKS = 1;",
        "",
        "INSERT INTO plant_species (species_id, name_en, name_hi, category) VALUES",
    ]

    plant_ids = {p: i + 1 for i, p in enumerate(plants)}
    rows = []
    for p in plants:
        name_en = p.replace("_", " ")
        name_hi = PLANT_HI.get(p)
        if name_hi is None:
            name_hi = name_en
            todos.append(f"plant Hindi name missing: {p}")
        cat = PLANT_CATEGORY.get(p, "horticulture")
        rows.append(f"  ({plant_ids[p]}, '{sql_escape(name_en)}', "
                    f"'{sql_escape(name_hi)}', '{cat}')")
    lines.append(",\n".join(rows) + ";")
    lines.append("")
    lines.append("INSERT INTO diseases (species_id, class_label, name_en, name_hi, severity) VALUES")

    rows = []
    for c in class_names:
        plant_key = c.partition("___")[0]
        disease_key = c.partition("___")[2]
        plant_disp, disease_disp = pretty(c)
        name_en = "Healthy" if disease_key == "healthy" else disease_disp.title()

        hi_entry = DISEASE_HI.get(disease_key)
        if hi_entry:
            name_hi, severity = hi_entry
        else:
            name_hi, severity = name_en, "moderate"
            todos.append(f"disease Hindi name missing: {c}")

        note = "" if c in HAS_REAL_WORLD_DATA else "  -- lab-only training data"
        rows.append(f"  ({plant_ids[plant_key]}, '{sql_escape(c)}', "
                    f"'{sql_escape(name_en)}', '{sql_escape(name_hi)}', "
                    f"'{severity}'){note}")
    lines.append(",\n".join(r.split("  --")[0].rstrip() for r in rows) + ";")
    lines.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} — {len(plants)} species, {len(class_names)} diseases")

    if todos:
        print(f"\n{len(todos)} item(s) need a human translation/review:")
        for t in sorted(set(todos)):
            print(f"  - {t}")

    print("\nApply with:  mysql -u root -p < " + str(out))
    print("Note: care_guides is truncated and NOT repopulated — the care text is\n"
          "agronomic advice, not something to auto-generate. Re-add rows for the\n"
          "diseases you actually surface in the UI.")


if __name__ == "__main__":
    main()
